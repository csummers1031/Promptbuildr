/**
 * Turn a PresentedGeneration (the same DTO the web app renders) into MCP tool
 * output: human-readable Markdown for `content`, plus a structured mirror for
 * `structuredContent`. Affiliate/tool links are preserved as Markdown links so
 * they stay clickable and keep their rel/campaign value wherever the client
 * renders them.
 *
 * Note: strings here are built with concatenation, not template literals, so
 * literal backtick code fences don't collide with JS template syntax.
 */
import type { PresentedGeneration } from "@/lib/present";
import type { InstructionSegment } from "@/lib/tools/render";

function segmentToMarkdown(seg: InstructionSegment): string {
  if (seg.type === "link") return "[" + seg.value + "](" + seg.href + ")";
  return seg.value;
}

function stepToMarkdown(step: InstructionSegment[]): string {
  return step.map(segmentToMarkdown).join("");
}

function stepToPlainText(step: InstructionSegment[]): string {
  return step.map((s) => s.value).join("");
}

/** A fence long enough to safely wrap body, even if body itself contains backtick runs. */
function fenceFor(body: string): string {
  let longest = 0;
  const runs = body.match(/`+/g);
  if (runs) for (const run of runs) longest = Math.max(longest, run.length);
  return "`".repeat(Math.max(3, longest + 1));
}

export function toMarkdown(p: PresentedGeneration): string {
  const lines: string[] = [];
  lines.push("# " + p.title);
  lines.push("");
  lines.push("## Prompt");
  lines.push("");
  const fence = fenceFor(p.prompt);
  lines.push(fence + "text");
  lines.push(p.prompt);
  lines.push(fence);

  if (p.instructions.length) {
    lines.push("");
    lines.push("## How to use it");
    lines.push("");
    p.instructions.forEach((step, i) => {
      lines.push(i + 1 + ". " + stepToMarkdown(step));
    });
  }

  const links = p.toolLinks.filter((l) => l.href);
  if (links.length) {
    lines.push("");
    lines.push("## Recommended tools");
    lines.push("");
    for (const l of links) lines.push("- [" + l.name + "](" + l.href + ")");
  }

  lines.push("");
  lines.push("---");
  lines.push("Generated by [Promptbuildr](https://promptbuildr.ai).");
  return lines.join("\n");
}

export function toStructured(p: PresentedGeneration): Record<string, unknown> {
  return {
    title: p.title,
    prompt: p.prompt,
    instructions: p.instructions.map(stepToPlainText),
    tools: p.toolLinks
      .filter((l) => l.href)
      .map((l) => ({ name: l.name, url: l.href as string })),
    categoryTags: p.categoryTags,
    isBusiness: p.isBusiness,
    aiTool: p.aiTool,
  };
}
